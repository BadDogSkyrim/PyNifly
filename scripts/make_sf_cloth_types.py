"""Generate io_scene_nifly/pyn/sf_cloth_types.py: the Havok type definitions PyNifly copies into
a Starfield cloth blob that lacks them (hclBendStiffnessConstraintSetMx and what it refers to).

The source is a vanilla cloth blob that has those types. Only its type section is kept -- type
and field names, layouts, hashes -- with every object dropped, so what's embedded is Havok class
metadata, no game content.

    python scripts/make_sf_cloth_types.py --assets "C:\\...\\00StarfieldAssets"
"""
import argparse
import base64
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                'io_scene_nifly'))
from pyn.pynifly import NifFile          # noqa: E402
from pyn.havok_tagwrite import TagDoc    # noqa: E402

SOURCE = ('meshes', 'actors', 'child', 'mesh', 'hairs', 'ponytail_hairmesh.nif')
NEEDED = ('hclBendStiffnessConstraintSetMx',)
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'io_scene_nifly', 'pyn', 'sf_cloth_types.py')


def types_only(blob):
    doc = TagDoc(blob)
    names = {doc.type_name(t) for t in range(1, len(doc.tna))}
    missing = [n for n in NEEDED if n not in names]
    if missing:
        raise SystemExit(f"source has no {missing}")
    doc.data = bytearray()
    doc.items = doc.items[:1]
    doc.patches = []
    return doc.to_bytes()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--assets', required=True, help="unpacked Starfield assets folder")
    args = ap.parse_args(argv)
    blob = NifFile(os.path.join(args.assets, *SOURCE)).cloth_data[0][1]
    data = base64.b64encode(types_only(blob)).decode('ascii')
    lines = [data[i:i + 96] for i in range(0, len(data), 96)]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""Havok type definitions for Starfield cloth, generated by '
                'scripts/make_sf_cloth_types.py\nfrom vanilla '
                f'{"/".join(SOURCE[1:])}: its type section only, no objects. Do not edit."""\n')
        f.write('import base64\n\nTYPES = base64.b64decode(\n')
        f.writelines(f"    '{line}'\n" for line in lines)
        f.write(')\n')
    print(f"wrote {OUT}: {len(blob)} -> {len(base64.b64decode(data))} bytes of types")


if __name__ == '__main__':
    main()
