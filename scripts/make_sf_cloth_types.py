"""Generate io_scene_nifly/pyn/sf_cloth_types.py: the Havok type definitions PyNifly writes
Starfield cloth with -- every type the 298 vanilla cloth blobs use, so the builder can write any
of them into a blob that lacks it.

The sources are vanilla cloth blobs that between them use all 272 types (a greedy cover, worked
out 2026-10-24), plus one for a definition only it has. Only their type sections are kept --
type and field names, layouts, hashes -- with every object dropped, so what's embedded is Havok
class metadata, no game content.

    python scripts/make_sf_cloth_types.py --assets "C:\\...\\00StarfieldAssets"
"""
import argparse
import base64
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                'io_scene_nifly'))
from pyn.pynifly import NifFile          # noqa: E402
from pyn.havok_tagwrite import TagDoc    # noqa: E402

SOURCES = [('meshes', 'actors', 'child', 'mesh', 'hairs', 'ponytail_hairmesh.nif'),
           ('meshes', 'actors', 'human', 'mesh', 'hairs', 'ponytail', 'ponytail_hairmesh_f.nif'),
           ('meshes', 'clothes', 'outfit_khan', 'outfit_khan_lowerbody_m.nif'),
           ('meshes', 'actors', 'human', 'mesh', 'hairs', 'messy_bob', 'messy_bob_f.nif'),
           ('meshes', 'clothes', 'spacesuit_miner', 'ssminer_backpack_m.nif'),
           ('meshes', 'actors', 'floatera', 'mesh', 'floatera_nautiloos', 'floatera_nautiloos.nif'),
           ('meshes', 'actors', 'quadrupedb', 'mesh', 'quadrupedb_aceles', 'quadrupedb_aceles.nif'),
           ('meshes', 'actors', 'human', 'mesh', 'hairs', 'hollywood_curls',
            'hollywood_curls_f.nif'),
           # The only kind of blob that defines hclCompressibleLinkConstraintSetMx::Single
           # (the others name it, with no body).
           ('meshes', 'actors', 'floatera', 'mesh', 'floatera_drone', 'floatera_drone.nif')]
NEEDED = ('hclBendStiffnessConstraintSetMx', 'hclLocalRangeConstraintSet', 'hclCapsuleShape',
          'hclTaperedCapsuleShape', 'hclSphereShape', 'hclBoneSpaceSkinPNOperator',
          'hclCopyVerticesOperator', 'hclBonePlanesConstraintSet',
          'hclCompressibleLinkConstraintSetMx', 'hclVolumeConstraintMx')
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'io_scene_nifly', 'pyn', 'sf_cloth_types.py')


def types_only(blobs):
    doc = TagDoc(blobs[0])
    for b in blobs[1:]:
        donor = TagDoc(b)
        for t in range(1, len(donor.tna)):
            doc.copy_type(donor, t)
    names = {doc.type_name(t) for t in range(1, len(doc.tna))}
    missing = [n for n in NEEDED if n not in names]
    if missing:
        raise SystemExit(f"sources have no {missing}")
    doc.data = bytearray()
    doc.items = doc.items[:1]
    doc.patches = []
    return doc.to_bytes()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--assets', required=True, help="unpacked Starfield assets folder")
    args = ap.parse_args(argv)
    blobs = [NifFile(os.path.join(args.assets, *src)).cloth_data[0][1] for src in SOURCES]
    data = base64.b64encode(types_only(blobs)).decode('ascii')
    lines = [data[i:i + 96] for i in range(0, len(data), 96)]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""Havok type definitions for Starfield cloth, generated by '
                'scripts/make_sf_cloth_types.py\nfrom the type sections of '
                f'{len(SOURCES)} vanilla cloth blobs, no objects. Do not edit."""\n')
        f.write('import base64\n\nTYPES = base64.b64decode(\n')
        f.writelines(f"    '{line}'\n" for line in lines)
        f.write(')\n')
    print(f"wrote {OUT}: {len(base64.b64decode(data))} bytes of types")


if __name__ == '__main__':
    main()
